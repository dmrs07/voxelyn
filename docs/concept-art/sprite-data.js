/* ============================================================
   Voxelyn Sprite Data — all 6 sprites
   All 4 facings (DR/DL/UR/UL) authored with base grids + procedural
   perspective rules. All 5 states (idle/walk/attack/hit/die) defined
   as frame sequences with squash/stretch + anticipation.
============================================================ */

/* ---------- Facing geometry helpers ----------
   DR = facing down-right (camera sees front-right of unit)
   DL = facing down-left  (front-left)
   UR = facing up-right   (back-right)
   UL = facing up-left    (back-left)
   For each sprite we author DR as master; UR is "back" variant
   (face becomes hood / hair, no eyes). DL / UL are horizontal
   mirrors of DR / UR with slight offset.
*/

function mirrorGrid(grid){
  return grid.map(row => [...row].reverse());
}

/* ---------- Generic body plan ----------
   buildFacings(masterDR, masterUR) -> {DR, DL, UR, UL}
*/
function buildFacings(DR, UR){
  return {
    DR,
    DL: mirrorGrid(DR),
    UR,
    UL: mirrorGrid(UR),
  };
}

/* Helper: convert each facing set into poseKey entries */
function posesFromFacings(base, facings){
  const out = {};
  for (const f of ["DR","DL","UR","UL"]){
    out[`${f}:${base}`] = facings[f];
  }
  return out;
}

