    const bob = pose === "idle_b" ? -1 : 0;
    const cx = 16;
    for (const s of [-1, 1]){
      line(g, cx + s*3, 23+bob, cx + s*6 + d.x, 29 + (s > 0 ? 0 : -2), c.dark, 0);
      flatDiamond(g, cx + s*6 + d.x, 29 + (s > 0 ? 0 : -2), 2, 1, c.dark, c.edge);
    }
    facetedDiamond(g, cx, 19+bob, 7, 6, c, d, {top:c.light, left:c.mid, right:c.light, front:c.dark});
    facetedDiamond(g, cx + d.x, 10+bob, 7, 4, c, d, {top:c.top, left:c.mid, right:c.light, front:c.dark});
    if (d.y > 0) flatDiamond(g, cx + d.x*3, 12+bob, 2, 1, c.accent, c.glow);
    else line(g, cx - d.x*4, 9+bob, cx + d.x*3, 8+bob, c.top, 0);
